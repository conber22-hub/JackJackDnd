// SRD 5.2.1, CC BY 4.0; attribution is retained in the generated overlay.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { SRD_MONSTERS } from '../src/data/srd-monsters.js';
import { timing } from './import-spell-conditions.mjs';
const abilities = { Strength:'str', Dexterity:'dex', Constitution:'con', Intelligence:'int', Wisdom:'wis', Charisma:'cha' };
const plain = s => s.replace(/<[^>]*>/g, '').replace(/&#x27;/g, "'").replace(/&amp;/g, '&');
export function parseAction(trait){
  const head = /^<b>(.*?)\.<\/b>\s*(.*)$/.exec(trait);
  if (!head) return null;
  const text = plain(head[2]);
  // Require a directly invoked save and immediate, single-type damage. No triggered traits or staged gazes.
  const save = /^(Strength|Dexterity|Constitution|Intelligence|Wisdom|Charisma) Saving Throw: DC (\d+),/.exec(text);
  const damage = /\bFailure: \d+ \((\d+d\d+(?:\s*[+-]\s*\d+)?)\) (\w+) damage/.exec(text);
  if (!save || !damage || /First Failure:|Second Failure:|\bplus \d+ \(|\b\d+\/Day/.test(head[1] + text)) return null;
  const cone = /(\d+)-foot (Cone|Cube|Sphere)/.exec(text);
  const line = /(\d+)-foot-long, (\d+)-foot-wide Line/.exec(text);
  const range = /within (\d+) feet/.exec(text);
  // Unexpressible targeting (space, emanation, swallowed targets) remains manual.
  if (!cone && !line && !range) return null;
  const action = { n:plain(head[1]).replace(/ \(Recharge.*\)$/, ''), k:'save', sv:abilities[save[1]], dc:+save[2], d:damage[1].replace(/\s/g, ''), ty:damage[2].toLowerCase(), half:/Success: Half damage/.test(text) };
  if (cone) { action.area = [cone[2].toLowerCase(), +cone[1]]; action.r = 0; }
  else if (line) { action.area = ['line', +line[1]]; action.r = 0; }
  else action.r = +range[1];
  const recharge = /Recharge (\d+)(?:[–-]\d+)?/.exec(head[1]);
  if (recharge) action.recharge = +recharge[1];
  const failure = text.split(/\bFailure: /)[1]?.split(/\bSuccess:|Failure or Success:/)[0] || '';
  const cond = /(?:target|creature) has the (\w+) condition/.exec(failure);
  if (cond){
    action.cond = cond[1].toLowerCase();
    // Only the primary condition's failure clause can supply its timing.
    const primary = failure.split('Failure by')[0];
    const tm = timing(primary);
    if (tm.dur && !/until the grapple ends|until the rope|swallowed|While Poisoned/.test(primary)) Object.assign(action, tm);
    else { delete action.cond; action.conditionManual = true; }
  }
  // Keep the full adjudication context, including width, prerequisites, durations and later saves.
  action.note = text;
  return action;
}
export function buildMonsterPlay(parseDefenses){
  return Object.fromEntries(SRD_MONSTERS.map(m => {
    const entry = { defenses:parseDefenses(m.traits), actions:m.traits.map(parseAction).filter(Boolean) };
    const text = m.traits.map(plain).join('\n');
    const legendary = /Legendary Action Uses: (\d+)/.exec(text);
    const resistance = /Legendary Resistance \((\d+)\/Day/.exec(text);
    if (legendary) entry.legendary = +legendary[1];
    if (resistance) entry.resistDaily = +resistance[1];
    return [m.id, entry];
  }));
}
