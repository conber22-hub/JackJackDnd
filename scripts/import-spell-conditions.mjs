// SRD 5.2.1 CC BY 4.0. Review gates prevent unrelated condition mentions becoming effects.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { SRD_SPELLS } from '../src/data/srd-spells.js';
const names = 'Blinded Charmed Deafened Frightened Grappled Incapacitated Invisible Paralyzed Petrified Poisoned Prone Restrained Stunned Unconscious';
const conditionRE = new RegExp(`\\b(${names.split(' ').join('|')}) condition\\b`, 'g');
const reviewed = new Set(['Animal Friendship','Banishment','Charm Monster','Charm Person','Color Spray','Greater Invisibility','Hold Monster','Hold Person','Invisibility','Mislead','Ray of Sickness','Storm of Vengeance','Sunbeam','Sunburst','Weird','Stinking Cloud']);
export function timing(text, duration = ''){
  const out = {repeat:null,endsOn:[],dur:null};
  const endSave = /at the (end|start) of each of (?:its|the target's) turns[^.]*?(?:repeat|sav)|(?:repeat[^.]*?save|saving throw) at the (end|start) of each of (?:its|the target's) turns/i.exec(text);
  if (endSave) out.repeat = (endSave[1] || endSave[2]).toLowerCase();
  const fixed = /until the (end|start) of (your|its|the [\w '-]+?'s) next turn/i.exec(text);
  if (fixed){ out.dur = {n:1,unit:'round'}; out.expires = {phase:fixed[1].toLowerCase(),who:fixed[2] === 'its' ? 'target' : 'source',next:true}; }
  else if (/until the end of the current turn/i.test(text)){ out.dur = {n:0,unit:'round'}; out.expires = {phase:'end',who:'current',next:false}; }
  else {
    const time = /for (\d+) (round|minute|hour)s?\b/i.exec(text) || /(\d+) (round|minute|hour)s?\b/i.exec(duration);
    if (time) out.dur = {n:+time[1],unit:time[2].toLowerCase()};
  }
  // Damage dealt by the subject is distinct from damage received by it.
  if (/(?:you or (?:one of )?your allies (?:deals?|damage)|you\s+or one of your allies deals)/i.test(text)) out.endsOn.push('damageByCasterOrAlly');
  if (/(?:ends?[^.]*if[^.]*takes (?:any )?damage|if[^.]*takes (?:any )?damage[^.]*ends?|ends early if the target takes damage)/i.test(text)) out.endsOn.push('damage');
  if (/(?:ends|ends early|ends immediately)[^.]*after[^.]*make(?:s)? an attack roll/i.test(text)) out.endsOn.push('attack','dealDamage','castSpell');
  return out;
}
export function buildSpellEffects(){
  const effects = {}, skipped = {};
  for (const s of SRD_SPELLS){
    const mentions = [...s.text.matchAll(conditionRE)];
    if (!mentions.length) continue;
    if (!reviewed.has(s.n)) { skipped[s.n] = 'Choice, dependent/staged condition, conditional ending, indefinite duration, or non-granting mention; retain source text for adjudication.'; continue; }
    const cond = mentions[0][1].toLowerCase();
    const tm = timing(s.text,s.dur);
    if (!tm.dur) throw new Error(`${s.n}: missing condition duration`);
    const ability = /\b(Strength|Dexterity|Constitution|Intelligence|Wisdom|Charisma) saving throw/i.exec(s.text);
    effects[s.n] = {cond,save:ability ? ability[1].slice(0,3).toLowerCase() : null,...tm,conc:!!s.conc,note:s.text};
  }
  return {effects,skipped};
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href){
  const {effects,skipped} = buildSpellEffects();
  writeFileSync(new URL('../src/data/spell-effects.js',import.meta.url),'/* SRD 5.2.1 by Wizards of the Coast LLC, https://www.dndbeyond.com/srd.\n   CC BY 4.0 https://creativecommons.org/licenses/by/4.0/legalcode.\n   Changes: reviewed condition timing overlay. Generated by scripts/import-spell-conditions.mjs. */\nexport const SPELL_EFFECTS = '+JSON.stringify(effects,null,2)+';\n');
  console.log(JSON.stringify({covered:Object.keys(effects),skipped},null,2));
}
