import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const raw = readFileSync(process.argv[2]), source = raw.toString('utf8'), feats = {};
const all = ['Str', 'Dex', 'Con', 'Int', 'Wis', 'Cha'];
for (const [, n, cat, req, text] of source.matchAll(/^#### (.+)\n\n_(Origin|General|Fighting Style|Epic Boon) Feat(?: \(Prerequisite: (.+)\))?_\n\n([\s\S]*?)(?=^#{3,4} |$(?![\s\S]))/gm)){
  const f = { cat, req:req || 'None', text:text.trim(), src:'SRD 5.2.1' };
  if (cat === 'Origin') f.origin = true;
  if (cat === 'Fighting Style') f.style = true;
  if (n === 'Magic Initiate') f.lists = { C:'Cleric', D:'Druid', W:'Wizard' };
  if (n === 'Skilled') f.skills = 3;
  if (n === 'Grappler') f.plus = ['Str', 'Dex'];
  if (cat === 'Epic Boon'){
    f.plus = n === 'Boon of Irresistible Offense' ? ['Str', 'Dex'] : n === 'Boon of Spell Recall' ? ['Int', 'Wis', 'Cha'] : [...all];
    f.max = 30;
  }
  if (text.includes('_Repeatable._')) f.repeatable = true;
  assert.ok(!feats[n], n); feats[n] = f;
}
assert.equal(Object.keys(feats).length, 17);
writeFileSync(new URL('../src/data/srd-feats.js', import.meta.url), `/* This work includes material from the System Reference Document 5.2.1 ("SRD 5.2.1") by Wizards of
   the Coast LLC, available at https://www.dndbeyond.com/srd. The SRD 5.2.1 is licensed under the
   Creative Commons Attribution 4.0 International License, available at
   https://creativecommons.org/licenses/by/4.0/legalcode.
   Changes: structured categories/prerequisites, existing engine flags and ability caps.
   Generated by scripts/import-srd-feats.mjs from the pinned conversion; feats.md SHA-256:
   ${createHash('sha256').update(raw).digest('hex')} */\nexport const SRD_FEATS = ${JSON.stringify(feats, null, 2)};\n`);
console.log('17 SRD feats: 4 Origin, 2 General, 4 Fighting Style, 7 Epic Boon.');
