/* THREE.js loader for the original Barovian GLBs. Version-aligned with Dread Delve's Three.js 0.169.
   No DOM, no global scene mutation, and no automatic collision edits. */
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { TERRAIN_INDEX } from './barovia-terrain-index.js';

/**
 * @param {object} options
 * @param {string} [options.baseURL='/assets/terrain/'] URL of copied public GLB files
 * @param {GLTFLoader} [options.loader] optional shared GLTFLoader
 */
export function createBaroviaTerrain({ baseURL = '/assets/terrain/', loader = new GLTFLoader() } = {}) {
  const loaded = new Map();
  const base = baseURL.replace(/\/*$/, '/') || '/';

  async function load(id) {
    if (!TERRAIN_INDEX[id]) throw new RangeError(`Unknown Barovian terrain asset: ${id}`);
    if (!loaded.has(id)) {
      const task = loader.loadAsync(base + id + '.glb').then(gltf => gltf.scene)
        .catch(e => { loaded.delete(id); throw e; });
      loaded.set(id, task);
    }
    return loaded.get(id);
  }

  /** A newly-cloned Object3D sharing GPU geometry/materials with other instances. */
  async function instance(id, { castShadow = true } = {}) {
    const obj = (await load(id)).clone(true);
    const spec = TERRAIN_INDEX[id];
    obj.userData.terrain = { id, category: spec.category, placement: spec.placement, size: [...spec.size] };
    obj.traverse(child => { if (child.isMesh) {
      child.castShadow = castShadow && spec.placement !== 'surface';
      child.receiveShadow = true;
    } });
    return obj;
  }

  /**
   * Place a plan item generated by planTerrain/featureAt at its occupied grid cell center.
   * `wx` and `wz` are Dread Delve's grid -> world helpers from render/scene.js.
   * y is the world ground height for that floor, typically floorY(ui.floor).
   */
  async function place(scene, placement, { wx, wz, groundY = 0, castShadow = true } = {}) {
    if (typeof wx !== 'function' || typeof wz !== 'function')
      throw new TypeError('Pass wx and wz from render/scene.js');
    const spec = TERRAIN_INDEX[placement.id];
    if (!spec) throw new RangeError(`Unknown terrain asset: ${placement.id}`);
    const item = await instance(placement.id, { castShadow });
    const [w,h] = placement.size || (placement.rot % 2 ? [...spec.size].reverse() : spec.size);
    item.position.set(wx(placement.x + (w - 1) / 2), groundY, wz(placement.y + (h - 1) / 2));
    item.rotation.y = (placement.rot || 0) * Math.PI / 2;
    scene.add(item);
    return item;
  }

  /** Prefetch deduplicates assets even when dozens of placements use the same ID. */
  async function prefetch(ids) {
    await Promise.all([...new Set(ids)].map(load));
  }

  /** Attach a terrain plan in parallel, keeping returned placement order stable. */
  async function placeAll(scene, plan, options) {
    await prefetch(plan.map(p => p.id));
    return Promise.all(plan.map(p => place(scene, p, options)));
  }

  /** Only dispose after removing all instances; their geometry/materials are shared. */
  async function dispose() {
    const scenes = await Promise.all(loaded.values());
    const geos = new Set(), materials = new Set();
    for (const obj of scenes) obj.traverse(child => {
      if (!child.isMesh) return;
      if (child.geometry) geos.add(child.geometry);
      for (const material of (Array.isArray(child.material) ? child.material : [child.material])) if (material) materials.add(material);
    });
    for (const geo of geos) geo.dispose();
    for (const material of materials) material.dispose();
    loaded.clear();
  }

  return { load, instance, place, prefetch, placeAll, dispose };
}
